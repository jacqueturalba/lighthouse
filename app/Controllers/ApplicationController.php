function form_token(): string { 
    return '<input type="hidden" name="_token" value="'.e($_SESSION['csrf']).'">'; 
}

function rate_limited(string $email): bool { 
    $s=db()->prepare('SELECT COUNT(*) FROM login_attempts WHERE email=? AND ip=? AND attempted_at>DATE_SUB(NOW(), INTERVAL '.(int)config('LOGIN_DECAY_MINUTES','15').' MINUTE)'); 
    $s->execute([$email,$_SERVER['REMOTE_ADDR']??'']); 
    return (int)$s->fetchColumn() >= (int)config('LOGIN_MAX_ATTEMPTS','5'); 
}

function reset_link(string $email): void
{
    $email = strtolower(trim($email));
    $token = bin2hex(random_bytes(32));

    db()->beginTransaction();

    try {

        db()->prepare(
            'DELETE FROM password_reset_tokens WHERE email=?'
        )->execute([$email]);

        db()->prepare(
            'INSERT INTO password_reset_tokens (email, token) VALUES (?, ?)'
        )->execute([
            $email,
            password_hash($token, PASSWORD_ARGON2ID)
        ]);

        db()->commit();

        send_reset_email($email, $token);

        log_event('password_reset_requested', [
            'email' => $email
        ]);

    } catch (Throwable $e) {

        if (db()->inTransaction()) {
            db()->rollBack();
        }

        throw $e;
    }
}

function valid_reset_token(string $email, string $token): bool
{
    $email = strtolower(trim($email));

    // Remove whitespace potentially introduced by email URL wrapping.
    $token = preg_replace('/\s+/', '', $token);

    if ($email === '' || $token === '') {
        return false;
    }

    $owners = db()->prepare('SELECT COUNT(*) FROM users WHERE email=? AND status="active"');
    $owners->execute([$email]);
    if ((int)$owners->fetchColumn() !== 1) return false;

    // Tokens generated by bin2hex(random_bytes(32))
    // must be exactly 64 hexadecimal characters.
    if (!preg_match('/\A[a-f0-9]{64}\z/', $token)) {
        return false;
    }

    $s = db()->prepare(
        'SELECT token, created_at
         FROM password_reset_tokens
         WHERE email=?'
    );

    $s->execute([$email]);

    $row = $s->fetch();

    if (!$row) {
        return false;
    }

    $expiresAt =
        strtotime($row['created_at']) +
        ((int) config('PASSWORD_RESET_MINUTES', '60') * 60);

    if ($expiresAt < time()) {
        return false;
    }

    return password_verify($token, $row['token']);
}

class ApplicationController
{
    public function dispatch(array $routeParameters = []): void
    {
        global $path, $method;

        if ($user=current_user()) { 
            if ($user['must_change_password'] && !in_array($path,['/profile','/profile/password','/logout'],true)) { 
                flash('error','You must change your temporary password before continuing.'); 
                redirect('/profile'); 
            } 
        }

        if ($path==='/login' && $method==='GET') { 
            if(current_user()) redirect('/'); 
            view('auth/login',['title'=>'Sign in'],false); 
            exit; 
        }

        if ($path==='/login' && $method==='POST') {
            csrf(); 
            $email=trim($_POST['email']??'');
            
            if(rate_limited($email)) { 
                log_event('login_rate_limited',['email'=>$email]); 
                flash('error','Too many attempts. Try again later.'); 
                redirect('/login'); 
            } 
            
            if(!attempt_login($email,$_POST['password']??'')) { 
                db()->prepare('INSERT INTO login_attempts (email,ip) VALUES (?,?)')->execute([$email,$_SERVER['REMOTE_ADDR']??'']); 
                log_event('login_failed',['email'=>$email]); 
                flash('error','Invalid email/serial number or password.');
                redirect('/login'); 
            } 
            
            db()->prepare('DELETE FROM login_attempts WHERE email=?')->execute([$email]); 
            $user=current_user(); 
            redirect($user['must_change_password'] ? '/profile' : '/'); 
        }

        if ($path==='/logout' && $method==='POST') { 
            csrf(); 
            logout(); 
            session_start(); 
            $_SESSION['csrf']=bin2hex(random_bytes(32)); 
            flash('success','You have been signed out.'); 
            redirect('/login'); 
        }

        if ($path==='/forgot-password' && $method==='GET') { 
            view('auth/forgot-password',
                ['title'=>'Reset password'],
                false); 
            exit; 
        }

        if ($path==='/forgot-password' && $method==='POST') { 
            csrf(); 
            $email=strtolower(trim($_POST['email']??'')); 
            $s=db()->prepare('SELECT COUNT(*) FROM users WHERE email=? AND status="active"');
            $s->execute([$email]); 
            if((int)$s->fetchColumn()===1) {
                try { 
                    reset_link($email); 
                } catch(Throwable $e) { 
                    log_event('password_reset_delivery_failed',['email'=>$email]); 
                } 
            } 
            flash('success','If that email is registered, a reset link has been sent.'); 
            redirect('/forgot-password'); 
        }

        if ($path === '/reset-password' && $method === 'GET') {

            $email = strtolower(
                trim((string) ($_GET['email'] ?? ''))
            );

            $token = preg_replace(
                '/\s+/',
                '',
                (string) ($_GET['token'] ?? '')
            );

            if (!valid_reset_token($email, $token)) {

                http_response_code(404);

                render(
                    'Reset link unavailable',
                    '<p class="bg-primary-subtle opacity-75 rounded p-4 text-primary-emphasis">This password reset link is invalid or expired.</p>',
                    false
                );

                exit;
            }

            view(
                'auth/reset-password',
                [
                    'title' => 'Choose a new password',
                    'email' => $email,
                    'token' => $token
                ],
                false
            );

            exit;
        }

        if ($path === '/reset-password' && $method === 'POST') {

            csrf();

            $email = strtolower(
                trim((string) ($_POST['email'] ?? ''))
            );

            $token = preg_replace(
                '/\s+/',
                '',
                (string) ($_POST['token'] ?? '')
            );

            $password = (string) ($_POST['password'] ?? '');
            $confirmPassword = (string) ($_POST['confirm_password'] ?? '');

            $error =
                valid_password($password)
                ?: (
                    $password !== $confirmPassword
                        ? 'Passwords do not match.'
                        : null
                );

            if (!valid_reset_token($email, $token)) {
                $error = 'This reset link is invalid or expired.';
            }

            if ($error) {

                flash('error', $error);

                redirect(
                    '/reset-password?email=' .
                    rawurlencode($email) .
                    '&token=' .
                    rawurlencode($token)
                );
            }

            db()->beginTransaction();

            try {

                $targets=db()->prepare('SELECT id FROM users WHERE email=? AND status="active" FOR UPDATE');
                $targets->execute([$email]);
                $userIds=$targets->fetchAll(PDO::FETCH_COLUMN);
                if(count($userIds)!==1)throw new RuntimeException('This email belongs to more than one account. Sign in with your serial number.');

                db()->prepare(
                    'UPDATE users
                    SET password=?, must_change_password=0
                    WHERE id=?'
                )->execute([
                    password_hash($password, PASSWORD_ARGON2ID),
                    $userIds[0]
                ]);

                db()->prepare(
                    'DELETE FROM password_reset_tokens
                    WHERE email=?'
                )->execute([$email]);

                db()->commit();

                log_event('password_reset', [
                    'email' => $email
                ]);

            } catch (Throwable $e) {

                db()->rollBack();

                if ($e instanceof RuntimeException && str_contains($e->getMessage(),'more than one account')) {
                flash('error','This email belongs to more than one account. Sign in with your serial number.');
                    redirect('/login');
                }

                throw $e;
            }

            flash(
                'success',
                'Password changed. You can now sign in.'
            );

            redirect('/login');
        }

        if ($path==='/register' && $method==='GET') { 
            require_super_admin(); 
            view('auth/register',['title'=>'Create account']);
            exit; 
        }

        if ($path==='/register' && $method==='POST') { 
            
            require_super_admin(); 
            csrf(); 
            
            $serialNo=trim($_POST['serial_no']??'');
            $email=strtolower(trim($_POST['email']??''));
            $error=valid_password($_POST['password']??'') ? : (($_POST['password']??'')!==($_POST['confirm_password']??'')?'Passwords do not match.':null); 
            if($serialNo==='' || mb_strlen($serialNo)>100)$error='Enter a valid serial number.';
            if($email!=='' && !filter_var($email,FILTER_VALIDATE_EMAIL))$error='Enter a valid email.';

            if($error){
                flash('error',$error);
                redirect('/register');
            } 

            try{
                db()->prepare('INSERT INTO users (serial_no,name,email,password,role,must_change_password) VALUES (?,?,?,?,?,1)')->execute([$serialNo,trim($_POST['name']??''),$email ?: null,password_hash($_POST['password'],PASSWORD_ARGON2ID),'admin']);
                log_event('user_created',['serial_no'=>$serialNo,'email'=>$email]);flash('success','Account created.');

            }catch(PDOException $e){
                flash('error','That serial number already belongs to an account.');
            } 
            redirect('/users'); 
        }

        if ($path==='/profile' && $method==='GET') { 
            $u=require_auth(); 
            view('profile/profile',['title'=>'Profile','u'=>$u]); 
            exit; 
        }

        if ($path==='/profile/password' && $method==='POST') { 
            $u=require_auth(); 
            csrf(); 
            $s=db()->prepare('SELECT password FROM users WHERE id=?');
            $s->execute([$u['id']]);$old=$s->fetchColumn(); 
            $error=null; 
            if(!password_verify($_POST['current_password']??'',$old)) $error='Current password is incorrect.'; 
            elseif($error=valid_password($_POST['password']??'')) {

            } elseif(($_POST['password']??'')!==($_POST['confirm_password']??'')) $error='Passwords do not match.'; 
            elseif(password_verify($_POST['password'],$old)) $error='New password must differ from current password.'; 
            
            if($error){
                flash('error',$error);redirect('/profile');
            } 
            db()->prepare('UPDATE users SET password=?,must_change_password=0 WHERE id=?')->execute([password_hash($_POST['password'],PASSWORD_ARGON2ID),$u['id']]);
            session_regenerate_id(true);
            log_event('password_changed',['user_id'=>$u['id']]);
            flash('success','Password changed.');
            redirect('/profile'); 
        }

        if ($path==='/users' && $method==='GET') { 
            require_super_admin(); 
            $search=trim((string)($_GET['q']??''));
            $page=max(1,(int)($_GET['page']??1));
            $pageSize=25;
            $where=''; $params=[];
            if($search!==''){
                $where=' WHERE CONCAT_WS(" ",serial_no,name,email,church,hq_dept,ph_dept,region,area,birthday,contact_number,role,status,CAST(id AS CHAR),CAST(must_change_password AS CHAR),created_at,updated_at,last_login_at) LIKE ? ESCAPE "!"';
                $needle='%'.strtr($search,['!'=>'!!','%'=>'!%','_'=>'!_']).'%';
                $params[]=$needle;
            }
            $count=db()->prepare('SELECT COUNT(*) FROM users'.$where);
            $count->execute($params);
            $total=(int)$count->fetchColumn();
            $pages=max(1,(int)ceil($total/$pageSize));
            $page=min($page,$pages);
            $list=db()->prepare('SELECT id,serial_no,name,email,church,hq_dept,ph_dept,region,area,birthday,contact_number,role,status,created_at,last_login_at FROM users'.$where.' ORDER BY created_at DESC,id DESC LIMIT ? OFFSET ?');
            foreach($params as $i=>$value)$list->bindValue($i+1,$value,PDO::PARAM_STR);
            $list->bindValue(count($params)+1,$pageSize,PDO::PARAM_INT);
            $list->bindValue(count($params)+2,($page-1)*$pageSize,PDO::PARAM_INT);
            $list->execute();
            view('profile/user-management',['title'=>'User Management','rows'=>$list->fetchAll(),'search'=>$search,'page'=>$page,'pages'=>$pages,'pageSize'=>$pageSize,'total'=>$total]);
            exit; 
        }

        if ($path==='/users/password' && $method==='POST') { 
            $actor=require_super_admin();
            csrf();
            $id=(int)($_POST['id']??0);
            $error=valid_password($_POST['password']??'') ?: (($_POST['password']??'')!==($_POST['confirm_password']??'')?'Passwords do not match.':null);
            if(!$id)$error='Invalid user.';
            if($error){
                flash('error',$error);
                redirect('/users');
            }
            db()->prepare('UPDATE users SET password=?,must_change_password=1 WHERE id=?')->execute([password_hash($_POST['password'],PASSWORD_ARGON2ID),$id]);
            log_event('admin_password_changed',['actor_id'=>$actor['id'],'user_id'=>$id]);
            flash('success','User password updated. They must change it after signing in.');
            redirect('/users'); 
        }

        if ($path==='/users/role' && $method==='POST') { 
            $actor=require_super_admin();
            csrf();
            $id=(int)($_POST['id']??0);
            $role=$_POST['role']==='super_admin'?'super_admin':'admin';
            if($id===$actor['id'] && $role!=='super_admin'){
                flash('error','You cannot remove your own Super Admin access.');
                redirect('/users');
            }
            db()->prepare('UPDATE users SET role=? WHERE id=?')->execute([$role,$id]);
            log_event('user_role_changed',['actor_id'=>$actor['id'],'user_id'=>$id,'role'=>$role]);
            flash('success','User role updated.');
            redirect('/users'); 
        }

        if ($path==='/users/reset' && $method==='POST') { 
            require_super_admin();
            csrf();
            $email=strtolower(trim($_POST['email']??''));
            $s=db()->prepare('SELECT COUNT(*) FROM users WHERE email=? AND status="active"');
            $s->execute([$email]);
            $emailCount=(int)$s->fetchColumn();
            if($emailCount===1){
                try{
                    reset_link($email);
                    flash('success','Password reset link sent.');
                }catch(Throwable $e){
                    flash('error','Could not send reset email. Check mail configuration.');
                }
            }
            redirect('/users');
        }

        http_response_code(404); 
        render('Not found','<p class="bg-primary-subtle opacity-75 rounded p-4 text-primary-emphasis">The requested page does not exist.</p>',false);

    }

}
