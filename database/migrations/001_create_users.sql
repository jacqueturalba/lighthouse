CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, serial_no VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(120) NULL, email VARCHAR(255) NULL, password VARCHAR(255) NOT NULL,
 church VARCHAR(255) NULL, hq_dept VARCHAR(255) NULL, ph_dept VARCHAR(255) NULL, region VARCHAR(255) NULL, area VARCHAR(255) NULL, birthday DATE NULL, contact_number VARCHAR(100) NULL,
 role ENUM('super_admin','admin') NOT NULL DEFAULT 'admin', status ENUM('active','inactive') NOT NULL DEFAULT 'active',
 must_change_password TINYINT(1) NOT NULL DEFAULT 0, last_login_at TIMESTAMP NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
